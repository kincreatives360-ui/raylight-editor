import { z } from 'zod';
import { BackgroundSchema, EasingSchema, Vec3Schema } from './schemaPrimitives';
import { GroupSchema, LayerSchema } from './schemaLayers';

export const FramingSchema = z.object({
  id: z.string(),
  name: z.string(),
  target: Vec3Schema,
  zoom: z.number().min(0.1).max(10),
  roll: z.number().optional(),
  orbit: z.number().optional(),
  tilt: z.number().optional(),
});

export const CameraKeyframeEndpointSchema = z.object({
  presetId: z.string().optional(),
  anchorX: z.number(),
  anchorY: z.number(),
  anchorZ: z.number().optional(),
  zoom: z.number().min(0.1).max(10),
  roll: z.number(),
  orbit: z.number(),
  tilt: z.number(),
  focalLength: z.number().min(10).max(300).optional(),
  fov: z.number().min(5).max(160).optional(),
});

export const CameraBlockSchema = z.object({
  id: z.string(),
  label: z.string().optional(),
  startMs: z.number().min(0),
  durationMs: z.number().min(50),
  fromFramingId: z.string(),
  toFramingId: z.string(),
  mode: z.enum(['dolly', 'zoom', 'dollyzoom', 'shake']),
  easing: EasingSchema,
  from: CameraKeyframeEndpointSchema.optional(),
  to: CameraKeyframeEndpointSchema.optional(),
  shake: z
    .object({
      from: z.number().min(0).max(100),
      to: z.number().min(0).max(100),
      frequency: z.number().min(0.1).max(10).optional(),
    })
    .optional(),
});

export const LightAnimationBlockSchema = z.object({
  sourceStartMs: z.number().optional(),
  sourceDurationMs: z.number().min(0).optional(),
  id: z.string(),
  label: z.string(),
  targetLightId: z.string().optional(),
  property: z.enum(['position', 'intensity', 'temperature', 'ambience', 'color', 'angle', 'penumbra']).optional(),
  startMs: z.number().min(0),
  durationMs: z.number().min(50),
  fromX: z.number(),
  fromY: z.number(),
  toX: z.number(),
  toY: z.number(),
  fromZ: z.number().optional(),
  toZ: z.number().optional(),
  fromIntensity: z.number(),
  toIntensity: z.number(),
  fromColor: z.string().optional(),
  toColor: z.string().optional(),
  fromTemperature: z.number().min(1000).max(15000).optional(),
  toTemperature: z.number().min(1000).max(15000).optional(),
  fromAngle: z.number().optional(),
  toAngle: z.number().optional(),
  fromPenumbra: z.number().min(0).max(1).optional(),
  toPenumbra: z.number().min(0).max(1).optional(),
  holdBefore: z.boolean().optional(),
  easing: EasingSchema,
});

export const EffectKeySchema = z.enum([
  'depthOfField',
  'bloom',
  'vignette',
  'motionBlur',
  'chromaticAberration',
  'filmGrain',
  'ghost',
  'colorGrade',
  'edgeFade',
  'glitch',
  'atmosphere',
  'gradientMap',
  'fishEye',
  'lensDistortion',
]);

export const SceneEffectAnimationBlockSchema = z.object({
  sourceStartMs: z.number().optional(),
  sourceDurationMs: z.number().min(0).optional(),
  id: z.string(),
  label: z.string(),
  effectKey: EffectKeySchema,
  startMs: z.number().min(0),
  durationMs: z.number().min(50),
  fromValue: z.number(),
  toValue: z.number(),
  easing: EasingSchema,
});

export const FocusBlockSchema = z.object({
  sourceStartMs: z.number().optional(),
  sourceDurationMs: z.number().min(0).optional(),
  id: z.string(),
  label: z.string().optional(),
  startMs: z.number().min(0),
  durationMs: z.number().min(10),
  fromZ: z.number(),
  toZ: z.number(),
  easing: EasingSchema,
});

export const ShotSchema = z.object({
  id: z.string(),
  isPlaceholder: z.boolean().optional(),
  name: z.string(),
  startMs: z.number().min(0),
  durationMs: z.number().min(200),
  lane: z.number().int().min(0).max(7),
  /** When true (default), inherit project.background. When false, use shot.background. */
  useProjectBackground: z.boolean().optional(),
  background: BackgroundSchema.optional(),
  layers: z.array(LayerSchema),
  groups: z.array(GroupSchema),
  framings: z.array(FramingSchema),
  cameraBlocks: z.array(CameraBlockSchema),
  focusBlocks: z.array(FocusBlockSchema).optional(),
  lightBlocks: z.array(LightAnimationBlockSchema).optional(),
  effectBlocks: z.array(SceneEffectAnimationBlockSchema).optional(),
  light: z.object({
    position: Vec3Schema,
    target: Vec3Schema.optional(),
    intensity: z.number().min(0),
    temperature: z.number().min(1000).max(15000),
    ambience: z.number().min(0).max(1),
    ambientColor: z.string().optional(),
    keyColor: z.string().optional(),
    environment: z.enum(['studio', 'softbox', 'strip-light', 'daylight', 'night-city', 'warehouse', 'custom']).optional(),
    shadowStrength: z.number().min(0).max(1).optional(),
    shadowSoftness: z.number().min(0).max(100).optional(),
    keyLightEnabled: z.boolean().optional(),
    keyIntensity: z.number().min(0).optional(),
    fillEnabled: z.boolean().optional(),
    fillIntensity: z.number().min(0).max(1).optional(),
    backgroundReceivesLight: z.boolean().optional(),
    toneMapping: z.enum(['none', 'neutral']).optional(),
    castShadow: z.boolean().optional(),
    showGizmos: z.boolean().optional(),
    sources: z.array(z.object({
      id: z.string(),
      name: z.string(),
      type: z.enum(['directional', 'point', 'spot', 'area', 'ambient']),
      enabled: z.boolean(),
      position: Vec3Schema,
      target: Vec3Schema.optional(),
      rotation: Vec3Schema.optional(),
      intensity: z.number().min(0),
      color: z.string(),
      temperature: z.number().min(1000).max(15000).optional(),
      distance: z.number().optional(),
      decay: z.number().optional(),
      angle: z.number().optional(),
      penumbra: z.number().min(0).max(1).optional(),
      width: z.number().optional(),
      height: z.number().optional(),
      castShadow: z.boolean().optional(),
      shadowStrength: z.number().min(0).max(1).optional(),
      shadowSoftness: z.number().min(0).max(100).optional(),
    })).optional(),
  }),
  effects: z.object({
    atmosphere: z.object({
      enabled: z.boolean(), fog: z.number().min(0).max(1), mist: z.number().min(0).max(1), haze: z.number().min(0).max(1),
      color: z.string(), depthEnabled: z.boolean(), start: z.number().min(0).max(1), reach: z.number().min(0.01).max(1), mistHeight: z.number().min(0).max(1),
    }).default({ enabled: false, fog: 0.6, mist: 0.07, haze: 0, color: '#dce8f2', depthEnabled: true, start: 0, reach: 1, mistHeight: 0.35 }),
    gradientMap: z.object({
      enabled: z.boolean(), stops: z.array(z.object({ at: z.number().min(0).max(1), color: z.string(), opacity: z.number().min(0).max(1).optional() })).min(2).max(8),
      blend: z.number().min(0).max(1), shift: z.number().min(-1).max(1), spread: z.number().min(0.01).max(2),
      blendMode: z.enum(['normal', 'multiply', 'screen', 'overlay', 'softLight', 'hardLight', 'difference', 'exclusion', 'lighten', 'darken', 'colorDodge', 'colorBurn']),
    }).default({ enabled: false, stops: [{ at: 0, color: '#171a45' }, { at: 0.45, color: '#f05a9d' }, { at: 1, color: '#ffbc62' }], blend: 1, shift: 0, spread: 1, blendMode: 'normal' }),
    fishEye: z.object({
      enabled: z.boolean(), amount: z.number().min(-1).max(1), centerX: z.number().min(-1).max(1), centerY: z.number().min(-1).max(1),
      scale: z.number().min(0.1).max(2), edgeMode: z.enum(['fill', 'balanced', 'none']),
    }).default({ enabled: false, amount: 0.52, centerX: 0, centerY: 0, scale: 1, edgeMode: 'balanced' }),
    lensDistortion: z.object({
      enabled: z.boolean(), mode: z.enum(['pinch', 'barrel']), strength: z.number().min(-1).max(1), centerX: z.number().min(-1).max(1), centerY: z.number().min(-1).max(1),
      edgeMode: z.enum(['fill', 'balanced', 'none']), measure: z.enum(['width', 'height', 'diagonal']),
    }).default({ enabled: false, mode: 'pinch', strength: 0.25, centerX: 0, centerY: 0, edgeMode: 'fill', measure: 'width' }),
    depthOfField: z.object({
      enabled: z.boolean(),
      target: Vec3Schema,
      focusRange: z.number().min(0).max(20),
      aperture: z.number().min(0.1).max(32),
      bokehScale: z.number().min(0).max(20),
      bokehShape: z.enum(['anamorphic', 'spherical', 'vintage', 'portrait']),
      focalLength: z.number().optional(),
      highlightThreshold: z.number().optional(),
      highlightIntensity: z.number().optional(),
      sceneSize: z.number().min(1).max(200).optional(),
      focusMode: z.enum(['point', 'subject']).optional(),
    }),
    bloom: z.object({
      enabled: z.boolean(),
      intensity: z.number().min(0).max(4),
      threshold: z.number().min(0).max(4),
      radius: z.number().min(0).max(4).optional(),
      softness: z.number().min(0).max(1).optional(),
      blendMode: z.enum(['screen', 'add', 'softLight']).optional(),
    }),
    vignette: z.object({
      enabled: z.boolean(),
      intensity: z.number().min(0).max(1),
      midpoint: z.number().min(0).max(1).optional(),
      roundness: z.number().min(0).max(2).optional(),
    }),
    motionBlur: z.object({
      enabled: z.boolean(),
      shutterAngle: z.number().min(0).max(360),
      samples: z.number().int().min(2).max(32).optional(),
      angle: z.number().min(-180).max(180).optional(),
      direction: z.enum(['camera', 'angle']).optional(), amount: z.number().min(0).max(0.1).optional(),
    }),
    chromaticAberration: z.object({
      enabled: z.boolean(),
      offset: z.number().min(0).max(0.1),
      verticalOffset: z.number().min(-0.1).max(0.1).optional(),
      edgeStrength: z.number().min(0).max(4).optional(),
      mode: z.enum(['lens', 'split']).optional(), angle: z.number().min(-180).max(180).optional(), softness: z.number().min(0).max(1).optional(),
      centerX: z.number().min(-1).max(1).optional(), centerY: z.number().min(-1).max(1).optional(),
      channelRed: z.number().min(-2).max(2).optional(), channelGreen: z.number().min(-2).max(2).optional(), channelBlue: z.number().min(-2).max(2).optional(),
      fringeColorAngle: z.number().min(-180).max(180).optional(),
    }),
    filmGrain: z.object({
      enabled: z.boolean(),
      intensity: z.number().min(0).max(1),
      size: z.number().min(0.1).max(32),
      softness: z.number().min(0).max(1).optional(),
      colorAmount: z.number().min(0).max(1).optional(), aspect: z.number().min(0.25).max(4).optional(), seed: z.number().int().optional(),
      stock: z.enum(['Tungsten 500', 'Kodak 5219', 'Fuji 400', 'Custom']).optional(),
      shadowStrength: z.number().min(0).max(1).optional(), midStrength: z.number().min(0).max(1).optional(), highlightStrength: z.number().min(0).max(1).optional(),
      midpoint: z.number().min(0).max(1).optional(), protectBlacks: z.boolean().optional(), blendMode: z.enum(['film', 'overlay', 'softLight', 'multiply']).optional(),
      motion: z.enum(['frame', '12fps', 'static']).optional(), smooth: z.boolean().optional(), perChannel: z.boolean().optional(),
    }),
    ghost: z.object({
      enabled: z.boolean(),
      opacity: z.number().min(0).max(1),
      offset: z.number().min(-1).max(1),
      blur: z.number().min(0).max(100),
      angle: z.number().min(-180).max(180).optional(),
      spread: z.number().min(0).max(4).optional(),
    }),
    colorGrade: z.object({
      enabled: z.boolean(),
      exposure: z.number().min(-4).max(4),
      contrast: z.number().min(0).max(4),
      saturation: z.number().min(0).max(4),
      temperature: z.number().min(-4).max(4).optional(),
      tint: z.number().min(-4).max(4).optional(),
      highlights: z.number().min(-1).max(1).optional(),
      shadows: z.number().min(-1).max(1).optional(),
      lift: z.number().min(-1).max(1).optional(), gamma: z.number().min(0.1).max(4).optional(), vibrance: z.number().min(-1).max(1).optional(),
      blackPoint: z.number().min(0).max(1).optional(), whitePoint: z.number().min(0).max(1).optional(),
    }),
    edgeFade: z.object({
      enabled: z.boolean(),
      top: z.number().min(0).max(1),
      bottom: z.number().min(0).max(1),
      left: z.number().min(0).max(1).optional(),
      right: z.number().min(0).max(1).optional(),
      softness: z.number().min(0).max(4).optional(),
      color: z.string().optional(),
    }),
    glitch: z.object({
      enabled: z.boolean(),
      intensity: z.number().min(0).max(1),
      bandSize: z.number().min(2).max(200).optional(),
      colorShift: z.number().min(0).max(2).optional(),
      mode: z.enum(['digital', 'analog', 'datamosh']).optional(), jitter: z.number().min(0).max(1).optional(), scanlines: z.number().min(0).max(1).optional(), seed: z.number().int().optional(),
    }),
  }),
  effectsOrder: z.array(EffectKeySchema),
  appliedEffects: z.array(EffectKeySchema).optional(),
  transition: z.object({
    type: z.enum(['cut', 'crossfade', 'push', 'slide']),
    durationMs: z.number().min(0),
    easing: EasingSchema,
  }),
});

